def icon_uri(name):
    name = ALIAS.get(name, name)
    inner = FEATHER.get(name, FEATHER["grid"])
    svg = ("<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='2' "
           "stroke-linecap='round' stroke-linejoin='round'>" + inner + "</svg>")
    return "data:image/svg+xml," + urllib.parse.quote(svg, safe="")


def mask_css(name):
    uri = icon_uri(name)
    return f'-webkit-mask: url("{uri}") center/contain no-repeat; mask: url("{uri}") center/contain no-repeat;'


def icon_css():
    """أصناف .ic و.ic-<name> لاستعمالها داخل HTML."""
    css = ("<style>.ic{display:inline-block;width:1.2em;height:1.2em;vertical-align:-0.22em;margin-inline-end:6px;"
           "background-color:currentColor;}")
    for name in FEATHER:
        css += f".ic-{name}{{{mask_css(name)}}}"
    return css + "</style>"


def ms(name):
    """أيقونة داخل HTML: ms('map')."""
    return f"<span class='ic ic-{ALIAS.get(name, name)}'></span>"
